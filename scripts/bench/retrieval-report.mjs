// Renders results.json into report.md. Only numbers present in the results are printed.

const ms = (value) => {
  if (value === undefined || value === null) return "n/a"; // a timed-out wall has no median (null once saved as JSON)
  if (value >= 100) return value.toFixed(0);
  return value.toFixed(value >= 10 ? 1 : 2);
};
const med = (runs) =>
  runs === undefined ? undefined : [...runs].sort((a, b) => a - b)[Math.floor(runs.length / 2)];
const row = (cells) => `| ${cells.join(" | ")} |`;
const table = (head, rows) => [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");
const mb = (bytes) => (bytes / 2 ** 20).toFixed(1);
const exec = (entry) => (entry?.status === "ok" ? ms(med(entry.runs)) : (entry?.status ?? "n/a"));
const range = (entry) =>
  entry?.runs ? `${ms(Math.min(...entry.runs))}-${ms(Math.max(...entry.runs))}` : "n/a";
const MAIN = new Set(["chunks", "chunk_embeddings"]);
// The scans that carry the cost: rows produced, rows thrown away by a filter, and loop count.
const scans = (entry) =>
  (entry?.summary?.scans ?? [])
    .filter((s) => MAIN.has(s.relation))
    .map(
      (s) =>
        `${s.type} ${s.relation}${s.index ? ` [${s.index}]` : ""} rows=${s.rows} filtered=${s.removedByFilter} loops=${s.loops}`,
    )
    .join("<br>");
const jit = (entry) => (entry?.jitMs === undefined ? "off" : `${ms(entry.jitMs)} ms`);
const wallMs = (w) => {
  if (!w) return "n/a";
  return w.timeout ? "timeout" : `${ms(w.median)} (${ms(w.min)}-${ms(w.max)}, n=${w.runs.length})`;
};
// Sum of two wall medians; a timeout or a missing measurement is never added as a number.
const sumMs = (a, b) => {
  if (a?.timeout || b?.timeout) return "timeout";
  return a?.median == null || b?.median == null ? "n/a" : ms(a.median + b.median);
};

function vectorSection(r) {
  const s5 = r.vector["explain-5"].summary;
  const s50 = r.vector["explain-50"].summary;
  return [
    "**Vector (exact cosine scan)**",
    table(
      [
        "limit",
        "EXPLAIN exec ms (median, min-max)",
        "planning ms",
        "rows returned",
        "shared hit / read blocks",
        "wall ms incl. tx (median, min-max)",
      ],
      [5, 50].map((n) => {
        const s = n === 5 ? s5 : s50;
        return [
          n,
          `${exec(r.vector[`explain-${n}`])} (${range(r.vector[`explain-${n}`])})`,
          ms(s?.planningMs),
          s?.rowsReturned,
          `${s?.sharedHit} / ${s?.sharedRead}`,
          wallMs(r.vector[`wall-${n}`]),
        ];
      }),
    ),
    `Main scans @50: ${scans(r.vector["explain-50"])}; JIT: ${jit(r.vector["explain-50"])}.`,
    `Three different query vectors, limit 50, wall median ms: ${(r.vectorQueries ?? []).map(ms).join(", ")}.`,
  ].join("\n\n");
}

function keywordSection(r) {
  const rows = Object.entries(r.keyword).map(([key, k]) => {
    const scan = `${scans(k["explain-50"])} (JIT ${jit(k["explain-50"])})`;
    return [
      key,
      `\`${k.query}\``,
      k.expects,
      k["returned-50"],
      `${exec(k["explain-5"])} / ${exec(k["explain-50"])}`,
      `${wallMs(k["wall-5"])} / ${wallMs(k["wall-50"])}`,
      mb(k["bytes-50"]),
      scan,
    ];
  });
  return [
    "**Keyword** (`to_tsvector('simple', content) @@ websearch_to_tsquery`, ranked by `ts_rank_cd`; no index)",
    table(
      [
        "case",
        "query",
        "matching chunks (planted)",
        "returned @50",
        "EXPLAIN exec ms @5 / @50",
        "wall ms @5 / @50",
        "MB returned @50",
        "scans @50",
      ],
      rows,
    ),
  ].join("\n\n");
}

function hybridSection(r) {
  const rows = Object.entries(r.hybrid).map(([key, h]) => {
    const sum = sumMs(r.vector["wall-50"], r.keyword[key]["wall-50"]);
    return [
      key,
      wallMs(h.wall),
      sum,
      ms(h.vectorOnlyWall5?.median),
      h.candidates,
      mb(h.candidateBytes),
      h.fusionMs.toFixed(3),
    ];
  });
  return [
    "**Hybrid** (vector 50 + keyword 50 in one transaction, then RRF to 20)",
    table(
      [
        "keyword case",
        "hybrid wall ms (median, min-max)",
        "vector@50 + keyword@50 medians",
        "vector-only @5 wall",
        "candidates",
        "MB of chunk text fetched",
        "fuseRrf ms/call",
      ],
      rows,
    ),
  ].join("\n\n");
}

export function renderReport(result) {
  const env = result.environment;
  const parts = [
    "# Retrieval benchmark (M2.2e)",
    "Generated by `scripts/bench/retrieval-bench.mjs`; do not edit by hand.",
    "## Environment",
    "```json",
    JSON.stringify(
      {
        ...env,
        startedAt: result.startedAt,
        completedAt: result.completedAt,
        datasetSha256: result.digests,
      },
      null,
      2,
    ),
    "```",
  ];
  for (const size of result.sizes) {
    parts.push(
      `## ${size.size} chunks per workspace`,
      vectorSection(size),
      keywordSection(size),
      hybridSection(size),
      `Transaction overhead (begin + two set_config + rollback), wall ms: ${wallMs(size.transactionOverhead)}.`,
    );
  }
  return `${parts.join("\n\n")}\n`;
}
